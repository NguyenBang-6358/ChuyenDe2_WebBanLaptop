export function resolveProductImageUrl(seed: string, label?: string): string {
  if (seed && /^(https?:\/\/|\/)/i.test(seed)) {
    return seed;
  }
  const text = `${seed || ""} ${label || ""}`.toLowerCase();
  for (const key of Object.keys(BRAND_PRODUCT_IMAGES)) {
    if (text.includes(key)) {
      return BRAND_PRODUCT_IMAGES[key];
    }
  }
  return "https://images.unsplash.com/photo-1603302576837-37561b2e2302?w=500&auto=format&fit=crop&q=80";
}

type Seed = Omit<Product, "variants" | "images" | "rating" | "reviewCount"> & {
  rating?: number;
  reviews?: number;
};

const seed = (s: Seed): Product => {
  const defaultImg = resolveProductImageUrl(s.slug, s.name);
  const mockImgs = [defaultImg, defaultImg, defaultImg, defaultImg];
  return {
    ...s,
    rating: s.rating ?? 0,
    reviewCount: s.reviews ?? 0,
    variants: mk(s.basePrice),
    images: mockImgs,
    anhDaiDien: defaultImg,
    description: s.description ?? "",
  };
};

