// Cache cho các sản phẩm lấy từ API (backend)
const apiProductsCache = new Map<string, Product>();

export function cacheApiProducts(productsList: Product[]) {
  productsList.forEach((p) => {
    apiProductsCache.set(p.id, p);
  });
}

export function cacheApiProduct(p: Product) {
  apiProductsCache.set(p.id, p);
}

export function getProductBySlug(slug: string): Product | undefined {
  const mockProduct = products.find((p) => p.slug === slug);
  if (mockProduct) return mockProduct;
  return Array.from(apiProductsCache.values()).find((p) => p.slug === slug);
}

export function getProductById(id: string): Product | undefined {
  const mockProduct = products.find((p) => p.id === id);
  if (mockProduct) return mockProduct;
  return apiProductsCache.get(id);
}

export function variantOriginalPrice(product: Product, variantIndex: number): number {
  const v = product.variants[variantIndex];
  const origBase = product.giaGoc !== undefined ? product.giaGoc : product.basePrice;
  return origBase + (v ? v.priceDelta : 0);
}

export function variantPrice(product: Product, variantIndex: number): number {
  const v = product.variants[variantIndex];
  const original =
    (product.giaGoc !== undefined ? product.giaGoc : product.basePrice) + (v ? v.priceDelta : 0);
  if (product.phanTramGiam && product.phanTramGiam > 0) {
    return Math.round(original * (1 - product.phanTramGiam / 100));
  }
  return product.basePrice + (v ? v.priceDelta : 0);
}

/** Deterministic placeholder gradient (no images bundled). */
export function gradientFor(seed: string): string {
  let h = 0;
  for (let i = 0; i < seed.length; i++) h = (h * 31 + seed.charCodeAt(i)) >>> 0;
  const h1 = h % 360;
  const h2 = (h1 + 40) % 360;
  return `linear-gradient(135deg, oklch(0.85 0.04 ${h1}) 0%, oklch(0.55 0.06 ${h2}) 100%)`;
}
